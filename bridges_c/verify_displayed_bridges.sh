#!/bin/sh
# verify_displayed_bridges.sh - parity check between the app and this directory.
#
# Reads the 14 bridge definitions out of ../assets/manual-boundary-data.js,
# writes each group of displayed excerpts into one translation unit with the
# headers and adapters its conversion note declares, and compiles every group
# with the strict flag set. This is what makes "the displayed C compiles with
# its declared dependencies" a checked claim rather than an assertion, and it
# fails if the app's text and this directory's text drift apart.
#
# It also prints, per bridge, whether the displayed code is byte-identical to
# the compiled-and-tested code in this directory once comments and blank lines
# are removed.
set -u
cd "$(dirname "$0")" || exit 1

OUT=${OUT:-./_build}/displayed
mkdir -p "$OUT"
STRICT="-std=c11 -Wall -Wextra -Wpedantic -Werror"
ADT=${ADT:-../../baseline_pristine/memorise_graph_c}

python3 -I - "$OUT" <<'PYEOF'
import json, re, sys, os

out = sys.argv[1]
raw = open("../assets/manual-boundary-data.js").read()
m = re.match(r"^window\.COMP2521_MANUAL_BRIDGES = Object\.freeze\((.*)\);\s*$",
             raw, re.S)
bridges = {b["id"]: b for b in json.loads(m.group(1))}

GROUPS = {
    "group_graph": (
        ['#include <stdbool.h>', '#include <stdio.h>', '#include <stdlib.h>',
         '#include "../../graph_unweighted.h"', '#include "../../queue.h"'],
        ["bfs", "dfs", "undirected-cycle", "components",
         "hamiltonian-path", "hamiltonian-circuit", "warshall"],
    ),
    "group_avl": (
        ['#include <stdbool.h>', '#include <stdlib.h>'],
        ["avl-insert-rebalance", "avl-search", "avl-delete"],
    ),
    "group_weighted": (
        ['#include <math.h>', '#include <stdbool.h>', '#include <stdio.h>',
         '#include <stdlib.h>',
         '#include "../../wgraph.h"'],
        ["dijkstra", "kruskal", "prim"],
    ),
    "group_radix": (
        ['#include <stdlib.h>'],
        ["radix-sort"],
    ),
}

for name, (headers, ids) in GROUPS.items():
    parts = [
        "/* GENERATED by verify_displayed_bridges.sh - do not edit.",
        " * The displayed bridge excerpts from assets/manual-boundary-data.js,",
        " * concatenated with the headers their conversion notes declare, so that",
        " * the app's own text is compiled.",
        " * Bridges in this unit: " + ", ".join(ids),
        " */",
    ]
    parts += headers
    for bid in ids:
        parts.append("\n/* ---- bridge id=%s ---- */" % bid)
        parts.append(bridges[bid]["code"])
    open(os.path.join(out, name + ".c"), "w").write("\n".join(parts) + "\n")

# parity against the compiled sources in this directory
def strip(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    lines = [ln.rstrip() for ln in text.splitlines()]
    return "\n".join(ln for ln in lines if ln.strip())

# A displayed excerpt is compared against its compiled source together with the
# header that declares its types, because a type declaration belongs in the
# header while the lesson shows it inline.
GRAPH = ("bridges_graph.c", "bridges_graph.h")
AVL = ("avl.c", "avl.h")
WEIGHTED = ("bridges_weighted.c", "bridges_weighted.h")
RADIX = ("radix_sort.c", "radix_sort.h")
SOURCES = {
    "bfs": GRAPH, "dfs": GRAPH, "undirected-cycle": GRAPH, "components": GRAPH,
    "hamiltonian-path": GRAPH, "hamiltonian-circuit": GRAPH, "warshall": GRAPH,
    "avl-insert-rebalance": AVL, "avl-search": AVL, "avl-delete": AVL,
    "dijkstra": WEIGHTED, "kruskal": WEIGHTED, "prim": WEIGHTED,
    "radix-sort": RADIX,
}
cache = {}
print("parity of the displayed excerpt against the compiled source:")
missing = 0
for bid, src in SOURCES.items():
    if src not in cache:
        cache[src] = "\n".join(strip(open(f).read()) for f in src)
    excerpt = strip(bridges[bid]["code"])
    # every function definition in the excerpt must appear in the source
    chunks = [c for c in re.split(r"\n(?=\S)", excerpt) if c.strip()]
    absent = [c.splitlines()[0][:60] for c in chunks if c not in cache[src]]
    status = "same" if not absent else "DIFFERS"
    if absent:
        missing += 1
    print("  %-22s %-34s %s" % (bid, " + ".join(src), status))
    for a in absent:
        print("      not found: %s" % a)
print("bridges whose displayed text differs from the compiled text: %d" % missing)
sys.exit(1 if missing else 0)
PYEOF
parity=$?

rc=0
for f in "$OUT"/group_*.c; do
    # shellcheck disable=SC2086
    gcc $STRICT -I "$ADT" -c "$f" -o "$f.o"
    status=$?
    echo "compile displayed $(basename "$f"): exit $status"
    [ $status -ne 0 ] && rc=1
done

echo "displayed-excerpt parity check: exit $parity"
echo "displayed-excerpt compile:      exit $rc"
[ $parity -ne 0 ] && rc=1
exit $rc
